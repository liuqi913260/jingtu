const assert = require('assert');
const core = require('../src/core.js');
const adapter = { data: new Map(), getItem(k){ return this.data.get(k) ?? null; }, setItem(k,v){ this.data.set(k,String(v)); }, removeItem(k){ this.data.delete(k); } };
let store = core.makeStore();
assert.equal(store.schemaVersion, 1);
assert.equal(store.data.competitions.length, 4);
assert.equal(store.data.recruitments.length, 3);
assert.equal(store.data.knowledge.length, 6);
const user = core.register(store, {account:'a@example.com', password:'pw', name:'小林', school:'测试大学'});
assert.equal(core.currentUser(store).name, '小林');
core.logout(store);
assert.throws(() => core.addCompetition(store, {name:'x', organizer:'o', content:'c'}), /请先登录/);
core.login(store, 'a@example.com', 'pw');
const competition = core.addCompetition(store, {name:'测试比赛', organizer:'测试主办方', content:'测试内容', category:'创新创业', deadline:'2026-12-31'});
const recruitment = core.addRecruitment(store, {title:'测试招募', description:'需要伙伴', roles:['开发'], contestId:competition.id});
assert.equal(store.data.competitions[0].authorId, user.id);
assert.equal(store.data.recruitments[0].authorId, user.id);
assert.equal(core.toggleFavorite(store, 'competition', competition.id), true);
assert.equal(core.isFavorite(store, 'competition', competition.id), true);
const plan1 = core.addPlan(store, 'competition', competition.id, '准备比赛');
const plan2 = core.addPlan(store, 'competition', competition.id, '准备比赛');
assert.equal(plan1.id, plan2.id);
core.togglePlan(store, plan1.id);
assert.equal(store.data.todayPlans[0].completed, true);
const backup = core.exportBackup(store);
assert.ok(backup.exportedAt);
function hasPassword(value){ if(Array.isArray(value)) return value.some(hasPassword); if(value && typeof value==='object') return Object.entries(value).some(([k,v])=>k==='password'||hasPassword(v)); return false; }
assert.equal(hasPassword(backup), false);
assert.doesNotThrow(() => core.validateBackup(backup));
const restored = core.importBackup(backup);
assert.equal(restored.data.competitions[0].name, '测试比赛');
core.saveToAdapter(restored, adapter);
assert.equal(core.loadFromAdapter(adapter).data.competitions.length, 5);
const legacyAdapter = { data: new Map(), getItem(k){ return this.data.get(k) ?? null; }, setItem(k,v){ this.data.set(k,String(v)); } };
legacyAdapter.setItem('jt_user', JSON.stringify({email:'legacy@example.com',name:'旧用户',school:'旧学校'}));
legacyAdapter.setItem('jt_competitions', JSON.stringify([{id:'legacy',name:'旧比赛',school:'旧主办方',content:'旧内容'}]));
const migrated = core.loadFromAdapter(legacyAdapter);
assert.equal(migrated.data.competitions[0].id, 'legacy');
assert.equal(migrated.data.users[0].account, 'legacy@example.com');
assert.throws(() => core.validateBackup({app:'wrong',schemaVersion:1,data:{}}), /不是竞途/);
console.log('Phase 1 data: PASS');
